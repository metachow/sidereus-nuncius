"""Find the stars of one of Galileo's star charts on a cleaned scan and write a
TikZ redrawing.

usage: python tools/star_chart.py SCAN x0 y0 x1 y1 NAME [--minsize PX] [--drop i,j,...]
  box in work/pages/ pixels (1/3 of full size). Writes
    figures/chart_NAME.tex          TikZ picture at the 1610 size (1 unit = 1 mm)
    build/chart_NAME_check.png      the scan with every detected star numbered,
                                    red = large (known) star, blue = small (new) star
  --drop removes detections by number (dust, broken type), after checking the image.

Galileo drew the stars already known larger, with a double outline, and the new
ones smaller with a single line; in print the large ones are hollow six-pointed
stars and the small ones solid six-spoked asterisks. A detection is "large" when
its centre is empty (hollow outline) or it is clearly bigger than the median.
"""
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as ndi

scan = sys.argv[1]
x0, y0, x1, y1 = (int(v) * 3 for v in sys.argv[2:6])
name = sys.argv[6]
minsize = int(sys.argv[sys.argv.index('--minsize') + 1]) if '--minsize' in sys.argv else 28
drop = set()
if '--drop' in sys.argv:
    drop = {int(v) for v in sys.argv[sys.argv.index('--drop') + 1].split(',') if v}

im = np.asarray(Image.open(f'scans/{scan}.png').convert('L'))[y0:y1, x0:x1]
ink = im < 120
blob, n = ndi.label(ndi.binary_dilation(ink, iterations=3))
stars = []
for i, s in enumerate(ndi.find_objects(blob)):
    h = s[0].stop - s[0].start; w = s[1].stop - s[1].start
    d = max(h, w)
    if d < minsize or d > 260 or max(h, w) > 2.2 * min(h, w):
        continue                                   # dust, text, long scratches
    comp = ink[s] & (blob[s] == i + 1)
    cy, cx = ndi.center_of_mass(comp)
    ch, cw = comp.shape
    centre = comp[int(ch * 0.38):int(ch * 0.62), int(cw * 0.38):int(cw * 0.62)]
    hollow = centre.size > 0 and centre.mean() < 0.12
    stars.append([s[1].start + cx, s[0].start + cy, d, hollow])

# --dropxy "x,y;..." : remove detections near these points (full-resolution px within the box)
# --split  "x,y;..." : a detection near this point is two touching stars; split it along its long axis
def _pts(flag):
    if flag not in sys.argv:
        return []
    return [tuple(float(v) for v in p.split(',')) for p in sys.argv[sys.argv.index(flag) + 1].split(';') if p]


for px, py in _pts('--dropxy'):
    stars = [s for s in stars if np.hypot(s[0] - px, s[1] - py) > 60]
for px, py in _pts('--split'):
    j = min(range(len(stars)), key=lambda i: np.hypot(stars[i][0] - px, stars[i][1] - py))
    x, y, d, hollow = stars.pop(j)
    lab = blob[int(y), int(x)] if blob[int(y), int(x)] else None
    ys, xs = np.nonzero(blob == lab) if lab else (np.array([y]), np.array([x]))
    c = np.cov(np.stack([xs, ys]))
    v = np.linalg.eigh(c)[1][:, -1]                       # long axis
    t = (xs - xs.mean()) * v[0] + (ys - ys.mean()) * v[1]
    for half in (t < 0, t >= 0):
        stars.append([xs[half].mean(), ys[half].mean(), d * 0.62, False])

med = np.median([st[2] for st in stars]) if stars else 1
classified = [(x, y, d, (hollow and d > 1.15 * med) or d > 1.7 * med) for x, y, d, hollow in stars]
if '--allsmall' in sys.argv:            # a chart of new stars only (e.g. the head of Orion)
    classified = [(x, y, d, False) for x, y, d, _ in classified]
bigs = [(x, y, d) for x, y, d, large in classified if large]
out_stars = []
k = 0
for x, y, d, large in classified:
    if d < 0.6 * med:
        continue                       # broken spokes, dust
    if not large and any(np.hypot(x - bx, y - by) < bd * 0.45 for bx, by, bd in bigs):
        continue                       # the dot printed in the middle of a large star
    k += 1
    out_stars.append((k, x, y, d, large))

# check image
prev = Image.fromarray(im).convert('RGB')
dr = ImageDraw.Draw(prev)
for k, x, y, d, large in out_stars:
    col = (200, 0, 0) if large else (0, 0, 220)
    if k in drop:
        col = (150, 150, 150)
    r = d / 2 + 6
    dr.ellipse([x - r, y - r, x + r, y + r], outline=col, width=4)
    dr.text((x + r + 2, y - r - 2), str(k), fill=col)
prev = prev.resize((prev.width // 2, prev.height // 2))
prev.save(f'build/chart_{name}_check.png')

# TikZ: 657 px per inch -> mm; y axis up
mm = 25.4 / 657
W, H = im.shape[1] * mm, im.shape[0] * mm
lines = [f'% {name}: {len(out_stars) - len(drop & {s[0] for s in out_stars})} stars, measured from scan {scan}',
         f'% generated by tools/star_chart.py; size {W:.0f} x {H:.0f} mm at the 1610 scale',
         r'\begin{tikzpicture}[x=1mm, y=1mm]',
         f'  \\useasboundingbox (0,0) rectangle ({W:.1f},{H:.1f});']
nl = ns = 0
for k, x, y, d, large in out_stars:
    if k in drop:
        continue
    X, Y = x * mm, H - y * mm
    if large:
        lines.append(f'  \\oldstar{{{X:.1f}}}{{{Y:.1f}}}{{{d * mm:.2f}}}')
        nl += 1
    else:
        lines.append(f'  \\newstar{{{X:.1f}}}{{{Y:.1f}}}{{{d * mm:.2f}}}')
        ns += 1
lines.append(r'\end{tikzpicture}')
open(f'figures/chart_{name}.tex', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(f'{name}: {nl} large + {ns} small stars, {W:.0f} x {H:.0f} mm, median glyph {med * mm:.1f} mm;'
      f' check build/chart_{name}_check.png')
